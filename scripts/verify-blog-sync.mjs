import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { parse } from 'yaml';
import { command } from './admin/workspace-io.mjs';
import { splitMarkdownSource } from '../src/shared/content/frontmatter.mjs';

const runtimeRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const output = process.env.DSI_QA_ROOT || (process.platform === 'win32' ? 'D:/ai-output/DSI Admin开发/回归' : os.tmpdir());
await fs.mkdir(output, { recursive: true });
const root = await fs.mkdtemp(path.join(output, 'blog-sync-'));
const repoRoot = path.join(root, 'repo');
await fs.mkdir(repoRoot);
const script = path.join(runtimeRoot, 'scripts/sync-obsidian-blog.mjs');
const run = (args) => command(process.execPath, [script, ...args], { cwd: repoRoot });
const metadata = (text) => parse(splitMarkdownSource(text).frontmatter);

const packageScripts = JSON.parse(await fs.readFile(path.join(runtimeRoot, 'package.json'), 'utf8')).scripts;
const steps = packageScripts.prebuild.split('&&').map((step) => step.trim());
assert(!steps.includes('npm run sync:blog'));
assert(steps.includes('npm run sync:origin'));
assert(steps.includes('npm run prepare:content'));
assert(steps.includes('npm run prepare:origin'));
assert(steps.includes('npm run links:apply'));
assert.equal((await run([])).code, 0);
assert.equal((await run(['--dry-run'])).code, 0);
assert.deepEqual(await fs.readdir(repoRoot), [], '不指定单篇时不得创建目录或写入博客副本');

const source = path.join(root, '原文.md');
const destination = path.join(repoRoot, 'src/content/blog/原文.md');
const original = '---\ntitle: 原文标题\ndescription: 原文摘要\ncompletion_date: 2024-05-06\nmediaId: private-source-id\n---\n原文正文\n';
const official = '---\ntitle: 旧标题\ndescription: 旧摘要\ncompletion_date: 2024-05-06\nmediaId: stable-site-id\ncustom: preserved\n---\n旧正文\n';
await fs.writeFile(source, original);
await fs.mkdir(path.dirname(destination), { recursive: true });
await fs.writeFile(destination, official);
await run([]);
assert.equal(await fs.readFile(destination, 'utf8'), official);
await run(['--file', source, '--dry-run']);
assert.equal(await fs.readFile(destination, 'utf8'), official);
await run(['--file', source]);
const synced = await fs.readFile(destination, 'utf8');
assert.equal(metadata(synced).title, '原文标题');
assert.equal(metadata(synced).mediaId, 'stable-site-id');
assert.equal(metadata(synced).custom, 'preserved');
assert.equal(splitMarkdownSource(synced).body, '\n原文正文\n');
assert.equal(await fs.readFile(source, 'utf8'), original);
await assert.rejects(run(['--file']));
await assert.rejects(run(['--file', path.join(root, '不存在.md')]));
assert.equal(await fs.readFile(destination, 'utf8'), synced);
console.log(`[pass] Default publishing-copy sync retired; explicit file dry-run and source/site ownership preserved: ${root}`);
